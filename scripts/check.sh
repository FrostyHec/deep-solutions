#!/bin/bash
# =============================================================================
# deep-solutions 开发者一键检查脚本
# 用于在提交/发布前运行完整的代码检查流程
# =============================================================================

set -e  # 遇到错误立即退出

# 颜色定义
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# 打印带颜色的消息
print_header() {
    echo ""
    echo -e "${BLUE}============================================================${NC}"
    echo -e "${BLUE}  $1${NC}"
    echo -e "${BLUE}============================================================${NC}"
    echo ""
}

print_success() {
    echo -e "${GREEN}✓ $1${NC}"
}

print_error() {
    echo -e "${RED}✗ $1${NC}"
}

print_warning() {
    echo -e "${YELLOW}⚠ $1${NC}"
}

# 获取脚本所在目录的上级目录（项目根目录）
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"

cd "$PROJECT_ROOT"

echo ""
echo -e "${BLUE}========================================${NC}"
echo -e "${BLUE}  deep-solutions 代码检查脚本${NC}"
echo -e "${BLUE}========================================${NC}"
echo ""
echo "项目目录: $PROJECT_ROOT"
echo ""

# =============================================================================
# Step 1: 代码格式化
# =============================================================================
print_header "Step 1/4: 代码格式化 (ruff format)"

echo "正在格式化 src/ 和 tests/ ..."
ruff format src/ tests/
print_success "代码格式化完成"

# =============================================================================
# Step 2: Lint 检查
# =============================================================================
print_header "Step 2/4: Lint 检查 (ruff check)"

echo "正在检查代码问题..."
if ruff check src/ tests/; then
    print_success "Lint 检查通过"
else
    print_error "Lint 检查失败"
    echo ""
    echo "提示: 运行 'ruff check --fix src/ tests/' 自动修复部分问题"
    exit 1
fi

# =============================================================================
# Step 3: 类型检查
# =============================================================================
print_header "Step 3/4: 类型检查 (mypy)"

echo "正在进行类型检查..."
if mypy src/; then
    print_success "类型检查通过"
else
    print_error "类型检查失败"
    exit 1
fi

# =============================================================================
# Step 4: 运行测试
# =============================================================================
print_header "Step 4/4: 运行测试 (pytest)"

echo "正在运行测试..."
if pytest; then
    print_success "所有测试通过"
else
    print_error "测试失败"
    exit 1
fi

# =============================================================================
# 完成
# =============================================================================
echo ""
echo -e "${GREEN}========================================${NC}"
echo -e "${GREEN}  ✓ 所有检查通过！${NC}"
echo -e "${GREEN}========================================${NC}"
echo ""
echo "代码已准备好提交或发布。"
echo ""
